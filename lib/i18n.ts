export type MessageKey = keyof typeof zh;

const messages: Record<Locale, { [K in MessageKey]: string }> = { zh, en };

export function localeFromLanguage(language: string | null | undefined): Locale {
  return language?.toLowerCase().startsWith("zh") ? "zh" : "en";
}

/** Saved choice wins. Otherwise Chinese locales stay Chinese and everything else is English. */
export function chooseLocale(stored: string | null | undefined, language: string | null | undefined): Locale {
  if (stored === "zh" || stored === "en") return stored;
  return localeFromLanguage(language);
}

export function readLocale(): Locale {
  if (typeof window === "undefined") return "zh";
  try {
    return chooseLocale(localStorage.getItem(LOCALE_STORAGE_KEY), navigator.language);
  } catch {
    return localeFromLanguage(navigator.language);
  }
}

export function htmlLang(locale: Locale) {
  return locale === "zh" ? "zh-CN" : "en";
}

export function isMessageKey(value: string): value is MessageKey {
  return Object.prototype.hasOwnProperty.call(zh, value);
}

export function t(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  const template = messages[locale][key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

export type Note = { key: MessageKey; vars?: Record<string, string | number> };

export function note(key: MessageKey, vars?: Record<string, string | number>): Note {
  return vars ? { key, vars } : { key };
}

/** Stable error id. Optional JSON vars ride after `|` so the UI can translate later. */
export function code(key: MessageKey, vars?: Record<string, string | number>) {
  return vars ? `${key}|${JSON.stringify(vars)}` : key;
}

export function parseNote(value: string): Note | null {
  const bar = value.indexOf("|");
  const key = bar === -1 ? value : value.slice(0, bar);
  if (!isMessageKey(key)) return null;
  if (bar === -1) return { key };
  try {
    const vars = JSON.parse(value.slice(bar + 1)) as Record<string, string | number>;
    if (!vars || typeof vars !== "object") return { key };
    return { key, vars };
  } catch {
    return { key };
  }
}

export function errorNote(error: unknown, fallback: MessageKey): Note {
  const raw = error instanceof Error ? error.message : "";
  return parseNote(raw) ?? note(fallback);
}
