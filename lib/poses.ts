import type { BuiltinClipId, Joints, PlayerDraft } from "./types.ts";

export type PoseCategory = "daily" | "combat" | "adventure" | "poster";

export type PosePreset = {
  id: string;
  name: string;
  hint: string;
  category: PoseCategory;
  recommendedClip?: BuiltinClipId;
  joints: Joints;
};

const z: Joints = {
  headX: 0,
  headY: 0,
  bodyX: 0,
  rArmX: 0,
  rArmZ: -7,
  rElbow: 0,
  lArmX: 0,
  lArmZ: 7,
  lElbow: 0,
  rLegX: 0,
  rKnee: 0,
  lLegX: 0,
  lKnee: 0,
};

function pose(partial: Partial<Joints>): Joints {
  return { ...z, ...partial };
}

export function mirrorJoints(joints: Joints): Joints {
  return {
    headX: joints.headX,
    headY: -joints.headY,
    bodyX: joints.bodyX,
    rArmX: joints.lArmX,
    rArmZ: -joints.lArmZ,
    rElbow: joints.lElbow,
    lArmX: joints.rArmX,
    lArmZ: -joints.rArmZ,
    lElbow: joints.rElbow,
    rLegX: joints.lLegX,
    rKnee: joints.lKnee,
    lLegX: joints.rLegX,
    lKnee: joints.rKnee,
  };
}

